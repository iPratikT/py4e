# Expression Execution
# we will check the arithmetic operations on string data type
name, age = "Pratik", 35
Txt="@"
A="2"
#string and numeric values can be operated together using the *
print(2*name*age)

#string and string values can be operated together using the +
print(2*(Txt+name))

# check how name, A and Txt are now operated:
print(2*(A+Txt+name))