tup=(1, 2, 3, 4, 522, 5, 6, 7, 8, 9, 10, 2, 3)

# slicing a tuple
print(tup[1:3]) 

# accessing elements of a tuple
print(tup[0])
print(tup[4])

# finding the first occurrence of an element in a tuple
print(tup.index(3))

# counting the number of occurrences of an element in a tuple
print(tup.count(2))